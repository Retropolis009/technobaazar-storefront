-- delivery cities, and richer orders (mirrors Alembic c41f2d90a7b3).
-- Safe to rerun.

CREATE TABLE IF NOT EXISTS category (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE,
  slug varchar(100) NOT NULL UNIQUE,
  sort_order integer NOT NULL DEFAULT 0,
  visible boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_category_slug ON category (slug);

ALTER TABLE product ADD COLUMN IF NOT EXISTS compare_at_price integer;
ALTER TABLE product ADD COLUMN IF NOT EXISTS track_stock boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS product_content (
  product_id integer PRIMARY KEY REFERENCES product(id) ON DELETE CASCADE,
  subtitle varchar(500) NOT NULL DEFAULT '',
  size varchar(100) NOT NULL DEFAULT '',
  gallery jsonb NOT NULL DEFAULT '[]'::jsonb,
  eyebrow varchar(200) NOT NULL DEFAULT '',
  intro text NOT NULL DEFAULT '',
  notes jsonb NOT NULL DEFAULT '[]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS guest_cart (
  token varchar(64) PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS guest_cart_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_token varchar(64) NOT NULL REFERENCES guest_cart(token) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
  quantity integer NOT NULL DEFAULT 1,
  UNIQUE (cart_token, product_id)
);
CREATE INDEX IF NOT EXISTS ix_guest_cart_item_cart_token ON guest_cart_item (cart_token);

CREATE TABLE IF NOT EXISTS coupon (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL,
  discount_type varchar(12) NOT NULL,
  value integer NOT NULL,
  minimum_subtotal integer NOT NULL DEFAULT 0,
  starts_at timestamptz,
  ends_at timestamptz,
  max_uses integer,
  used_count integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_coupon_code ON coupon (code);

CREATE TABLE IF NOT EXISTS store_setting (
  key varchar(80) PRIMARY KEY,
  value varchar(200) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS delivery_city (
  city_slug varchar(100) PRIMARY KEY,
  city_name varchar(120) NOT NULL,
  delivery_fee integer NOT NULL DEFAULT 350,
  active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0
);

ALTER TABLE "order" ALTER COLUMN customer_id DROP NOT NULL;
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS idempotency_key varchar(64);
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS discount_amount integer NOT NULL DEFAULT 0;
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS shipping integer NOT NULL DEFAULT 0;
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS coupon_code varchar(40) NOT NULL DEFAULT '';
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS email varchar(255) NOT NULL DEFAULT '';
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS city varchar(120) NOT NULL DEFAULT '';
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS postal_code varchar(20) NOT NULL DEFAULT '';
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS note varchar(500) NOT NULL DEFAULT '';
ALTER TABLE "order" ADD COLUMN IF NOT EXISTS stock_restored_at timestamptz;
CREATE INDEX IF NOT EXISTS ix_order_customer_id ON "order" (customer_id);
CREATE UNIQUE INDEX IF NOT EXISTS ix_order_idempotency_key ON "order" (idempotency_key);

CREATE TABLE IF NOT EXISTS order_stock_movement (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES "order"(id) ON DELETE CASCADE,
  product_id integer REFERENCES product(id) ON DELETE SET NULL,
  quantity integer NOT NULL,
  restored_at timestamptz,
  UNIQUE (order_id, product_id)
);
CREATE INDEX IF NOT EXISTS ix_order_stock_movement_order_id ON order_stock_movement (order_id);

CREATE TABLE IF NOT EXISTS site_content (
  content_key varchar(80) PRIMARY KEY,
  content_value text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS site_content_revision (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content jsonb NOT NULL,
  status varchar(20) NOT NULL,
  editor varchar(120) NOT NULL DEFAULT 'system',
  note varchar(240) NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_site_content_revision_status ON site_content_revision (status);
