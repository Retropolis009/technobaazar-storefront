-- 002: customers, carts, favorites, and orders (mirrors Alembic 9ac4b8d71e02).
-- Safe to rerun.

ALTER TABLE product ADD COLUMN IF NOT EXISTS stock_quantity integer NOT NULL DEFAULT 0;
ALTER TABLE product ADD COLUMN IF NOT EXISTS active boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS customer (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(255) NOT NULL,
  name varchar(160) NOT NULL,
  password_hash varchar(255) NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_customer_email ON customer (email);

CREATE TABLE IF NOT EXISTS cart_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
  quantity integer NOT NULL DEFAULT 1,
  UNIQUE (customer_id, product_id)
);

CREATE TABLE IF NOT EXISTS favorite (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
  UNIQUE (customer_id, product_id)
);

CREATE TABLE IF NOT EXISTS "order" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number varchar(40) NOT NULL UNIQUE,
  customer_id integer NOT NULL REFERENCES customer(id),
  status varchar(30) NOT NULL DEFAULT 'pending',
  payment_method varchar(30) NOT NULL DEFAULT 'cash_on_delivery',
  payment_status varchar(30) NOT NULL DEFAULT 'unpaid',
  subtotal integer NOT NULL,
  total integer NOT NULL,
  customer_name varchar(160) NOT NULL,
  phone varchar(40) NOT NULL,
  address text NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_order_order_number ON "order" (order_number);

CREATE TABLE IF NOT EXISTS order_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES "order"(id) ON DELETE CASCADE,
  product_id integer REFERENCES product(id) ON DELETE SET NULL,
  product_name varchar(240) NOT NULL,
  product_slug varchar(180) NOT NULL,
  unit_price integer NOT NULL,
  quantity integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_order_item_order_id ON order_item (order_id);
