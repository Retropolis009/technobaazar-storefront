-- 004: per-category specification shortcuts (mirrors Alembic d52e8f41b9c4).
-- The admin defines labels once per category; the product editor offers them
-- as one-click specification rows. Safe to rerun.

CREATE TABLE IF NOT EXISTS category_custom_field (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name varchar(100) NOT NULL,
  label varchar(100) NOT NULL,
  placeholder varchar(200) NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  UNIQUE (category_name, label)
);
CREATE INDEX IF NOT EXISTS ix_category_custom_field_category_name ON category_custom_field (category_name);
